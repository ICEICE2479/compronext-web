/** คำนวณความหนาแน่นพิกเซล (PPI) จากความกว้าง/สูงพิกเซลและขนาดทแยงนิ้ว */
export function calculateMonitorPpi(m: MonitorSpec): number {
  const diagPx = Math.hypot(m.resolution.width, m.resolution.height);
  return Math.round(diagPx / m.sizeInch);
}

export function describeMonitorClarity(ppi: number): {
  level: string;
  viewingDistanceCm: string;
} {
  if (ppi >= 150) {
    return { level: "คมชัดสูงมาก (ระดับ 4K HiDPI)", viewingDistanceCm: "50–70 ซม." };
  }
  if (ppi >= 105) {
    return { level: "คมชัดสมดุล (QHD Sweet-spot)", viewingDistanceCm: "60–80 ซม." };
  }
  return { level: "มาตรฐาน Full HD", viewingDistanceCm: "65–85 ซม." };
}
